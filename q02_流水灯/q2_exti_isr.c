/* ============================================================================
 * q02_流水灯/q2_exti_isr.c —— EXTI0 / EXTI1 的真正中断服务函数
 * ----------------------------------------------------------------------------
 * 【为什么 ISR 要单独一个文件，而不是直接写在 main_board.c 里】
 *   公共层 stm32f4_common.h 是**头文件实现**（函数体直接写在头里），
 *   里面已经用 weak 符号给全部 98 个中断入口都准备了默认实现：
 *       __attribute__((weak, used)) void EXTI0_IRQHandler(void) { for(;;){} }
 *   而 weak 符号只能被**另一个目标文件**里的同名强符号顶掉。
 *   在同一个文件里再写一遍 void EXTI0_IRQHandler(void){...} 是"重定义"，
 *   编译器直接报错——所以 ISR 必须单独成一个编译单元。
 *   （反过来，公共层也不能被两个 .c 同时 include，因为头文件里的函数体
 *     不是 inline，链接时会大面积 multiple definition。这也是它设计成
 *     "一个工程只编译一个 .c"的原因；q2 是唯一需要破例的题。）
 *
 * 【这个文件里刻意不 include stm32f4_common.h】
 *   include 了会和 main_board.c 里的那份重复定义、链接冲突；
 *   不 include 就只需要两个 extern 声明（下面这三个），
 *   也就不会出现"重新抄一遍寄存器定义"这种事——抄寄存器才是真正危险的。
 *
 * 【ISR 里做的事为什么只有这么多】
 *   ① 判断是不是本中断线（EXTI_PR 对上号）
 *   ② 清挂起位 —— **写 1 清**，不是写 0 清
 *   ③ 记时间戳、置事件计数
 *   就没了。点灯、改频率、串口打印全部留给主循环。
 *   理由见 main_board.c 文件头第 ② 条：ISR 的执行时间必须与外部事件的
 *   抖动次数无关，否则行为不可预测，而且一旦以后在 ISR 里加了串口打印，
 *   没有任何机制会提醒你"ISR 太长了"。
 * ==========================================================================*/

#include <stdint.h>   /* 只要固定宽度类型；寄存器一律从 main_board.c 那边拿 */

/* ---- 跨文件的共享量：定义在 main_board.c ---- */
extern volatile uint32_t g_dir_event;   /* 方向键事件计数 */
extern volatile uint32_t g_frq_event;   /* 频率键事件计数 */
extern volatile uint32_t g_last_edge;   /* 最近一次 EXTI 的时刻（用于弹跳过滤） */

/* ---- 公共层的毫秒时基：非 inline，extern 声明即可 ---- */
extern uint32_t millis(void);

/* ---- 清 EXTI 挂起位的薄封装（实现在 main_board.c）----
 * 为什么不在这里直接写 EXTI_PR(...)：那需要重新定义 REG 宏和 EXTI 基址，
 * 等于把公共层已经核对过的东西又手抄一遍。手抄的东西早晚会和母版跑偏。 */
extern void exti_line_clear(uint32_t line);

/* ============================================================================
 * EXTI0_IRQHandler —— 按键 1（PB0）：方向反转
 * ==========================================================================*/
void EXTI0_IRQHandler(void)
{
    exti_line_clear(0u);        /* 清挂起位 */
    g_last_edge = millis();     /* 记下这次沿的时刻，主循环用它判断弹跳 */
    ++g_dir_event;              /* 只置计数，方向由主循环改 */
}

/* ============================================================================
 * EXTI1_IRQHandler —— 按键 2（PB1）：频率切换
 * ==========================================================================*/
void EXTI1_IRQHandler(void)
{
    exti_line_clear(1u);
    g_last_edge = millis();
    ++g_frq_event;
}