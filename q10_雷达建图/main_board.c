/* ============================================================================
 * q10_雷达建图/main_board.c —— 第十题「盲人摸象」雷达扫描真板版
 * ----------------------------------------------------------------------------
 * 【和仿真版 main.c 的关系】
 *   扫描逻辑一行没改，这几样和仿真版完全一致：
 *     · 每步 5°（STEP_DEG）
 *     · 每步给舵机 200ms 到位窗口（STEP_DELAY_MS）
 *     · 往复：0°→180°→0°，到端点折返
 *     · 关键角度判定 angle % 90 == 0（即 0/90/180）
 *     · 串口报文格式 "角度:距离"，例如 "45:12.3"，行尾 \r\n
 *     · 关键角度额外发一行 "[LED] angle=90"
 *   只把两头接上真硬件：
 *       仿真：servo_set_angle() 把脉宽写 mailbox → 真板：写 TIM4->CCR1
 *       仿真：hcsr04_read_mm() 读 Python 写的 mailbox → 真板：真发 Trig 量 Echo
 *       仿真：UART4 + 阻塞 delay_ms() → 真板：USART1 + millis() 时间戳
 *
 *   【格式必须和 watch_radar.py 对得上，这点不能自作主张改】
 *     watch_radar.py 里是这么解析的：
 *         SCAN_LINE = ^(\d+):(\d+)\.(\d)\r?$      ← 抓 "45:67.0" 的 45/67/0
 *         LED_LINE  = ^\[LED\] angle=(\d+)\r?$     ← 抓 "[LED] angle=90" 的 90
 *     所以距离要打成**厘米.毫米位**两位小数，不是 "45:123"，
 *     也不能发成 "45:12.3 cm"——多一个空格整个正则就匹配不上，
 *     上位机会一个点都收不到，而且界面上看不出来，只会以为串口没通。
 *
 * ------------------------------------------------------------------
 * 一、接线表
 * ------------------------------------------------------------------
 *   PB6 (TIM4_CH1, AF2) ── SG90 信号线
 *   PB7 ── HC-SR04 的 Trig
 *   PB8 ── HC-SR04 的 Echo  ⚠ 必须先分压，见下 ⚠
 *   PB0 ── 关键角度提示 LED（高电平点亮）
 *   PA9 (USART1_TX, AF7) ── USB-TTL 的 RXD      115200-8-N-1
 *   PA10(USART1_RX, AF7) ── USB-TTL 的 TXD
 *
 *   ⚠⚠⚠ Echo 必须分压 ⚠⚠⚠
 *     HC-SR04 是 5V 供电，Echo 推挽输出接近 5V，F407 的 IO 超过 3.3V 就烧。
 *
 *        Echo ──┬── 1kΩ ──┬── PB8
 *                1kΩ      │
 *                        GND
 *
 *     用 1k/1k 分到 **1/2**（5V → 2.5V），而不是 1k/2k 的 1/3：
 *     F407 数字输入是施密特触发器，VIH 门限 = 0.7×VDD = 0.7×3.3 = **2.31V**。
 *     1/3 分压只得到 1.67V，**低于门限**，读出来是不可靠值——
 *     现象是"扫到某些角度才有数据、扫到别的角度全是 0.0"，
 *     很容易误以为是舵机角度没对，其实是电平没过门限。
 *     2.5V 高于 2.31V，才是真的"高"。
 *     （Q6 的红外 AO 接的是 ADC 模拟输入，那里 1/3 就够——
 *       数字脚和模拟脚对电压的要求不一样，别照抄。）
 *
 *   ⚠ SG90 和 HC-SR04 的 Vcc 都要接独立的 5V，**别从 F407 的 3.3V 取**。
 *     舵机和超声波模块在扫描过程中电流波动很大，3.3V 稳压器扛不住，
 *     表现是"扫到一半整块板子复位"——而那次复位后板子又是从 0° 重新开始的，
 *     看着像程序有 bug，其实是电源不够。
 *   ⚠ HC-SR04 必须和 STM32 共地。
 *   ⚠ SG90 装在 HC-SR04 **上方**，两个超声波探头要朝同一个方向。
 *     舵机转起来的时候线材会被缠住（俗称"拉线打结"），
 *     转几圈就缠死了，这题装的时候线要留足余量。
 *
 * ------------------------------------------------------------------
 * 二、这题真正要讲的技术点
 * ------------------------------------------------------------------
 *   要求①  0°→180°→0° 往复扫描        → sweep_advance() 里的折返判断
 *   要求②  实时测距并上报角度+距离      → 每一步：转好 → 等到位 → 测 → 报
 *   要求③  0/90/180 给 LED 提示        → angle % 90 == 0
 *   要求④  格式 "角度:距离" 可被上位机解析 → 见文件头的正则
 *
 *   ★ 真正想讲的是**"怎么让舵机到位"这件事本身**：
 *
 *     仿真版这里就是一行 delay_ms(200)。真板版换成"记下到位时刻，
 *     主循环拿 millis() 去比"，表面上只是写法变了，实际上有两点不同：
 *
 *     ① 舵机是**有惯性的机械件**，不是"给个值就瞬间到位"。
 *        200ms 是从"转 5°"到"基本停稳"的实测时间。
 *        用 delay_ms 会让整个主循环在这 200ms 里完全死掉：
 *        串口收不到东西、按键没反应、想加任何功能都得排队。
 *        换成时间戳之后主循环一直在跑，
 *        以后要加"按键暂停扫描""串口下指令改步长"，只要加一个 if。
 *
 *     ② 唯一还阻塞的是 HC-SR04 那 1~3ms 的测量，这个**必须阻塞**——
 *        超声波的飞行时间就那么长，测它只能靠"发出去然后等回波"，
 *        想同时干别的就只能上输入捕获+DMA，那是另一个档次的东西了。
 *        老实承认哪一段是阻塞的，比假装全程非阻塞要好。
 *        好在 200ms 的间隔远大于 3ms，节奏上看不出来。
 *
 *   ★ 还有一个雷达特有的真实问题：**两个超声波头之间会串扰**。
 *     SG90 的舵机是金属的机械结构，转动时会轻微震动。
 *     HC-SR04 对震动比较敏感，震动期间发射出去的超声波打到舵机自己身上，
 *     就得到一个很近的"回波"，实测表现为某些角度的距离会突然缩到 5~10cm。
 *     这是硬件的物理限制，软件只能靠滤波缓解（这里靠每步都重新测、
 *     上位机画图时自己剔毛刺），真正要根治得上带机械减振的结构件。
 *
 * ------------------------------------------------------------------
 * 三、几个时间/量程参数为什么这么取
 * ------------------------------------------------------------------
 *   STEP_DELAY_MS = 200ms：既是舵机 5° 步进的到位时间，也是扫描节奏。
 *     顺带满足了 HC-SR04 "两次发射间隔 ≥60ms"的要求（200 >> 60），
 *     所以不会读到上一次的残留回波。
 *   ECHO_MAX_US = 25000µs：25ms ≈ 431cm，远超 HC-SR04 的实际量程（4m 且
 *     4m 处已经基本收不到有效回波）。超过它就一定是没有回波，判 0 处理，
 *     同时保证传感器坏掉时主循环不会卡死。
 *   LED_PULSE_MS = 50ms：短到能看清、长到不至于让人等得不耐烦。
 * ==========================================================================*/

#include "stm32f4_common.h"

/* ============================ 引脚表 ============================
 * 换板子/换接线只改这一段。下面代码一行都不用动。 */
#define PIN_SERVO    PB6    /* TIM4_CH1, AF2 → SG90 信号线     */
#define PIN_TRIG     PB7    /* HC-SR04 Trig（普通推挽输出）   */
#define PIN_ECHO     PB8    /* HC-SR04 Echo，⚠ 接之前先分压到 3.3V 以内 */
#define PIN_LED      PB0    /* 关键角度提示 LED，高电平点亮    */
#define UART_TX      PA9    /* USART1_TX, AF7                 */
#define UART_RX      PA10   /* USART1_RX, AF7                 */

/* ============================ 扫描参数 ============================ */
#define STEP_DEG       5u   /* 每步 5°。和仿真版一样。
                                步子太大则每次转向的惯性和余振都更明显，
                                测出来的距离误差反而更大 */
#define STEP_DELAY_MS 200u  /* 每步的舵机到位窗口（同时也是扫描节奏）*/
#define LED_PULSE_MS   50u  /* 关键角度 LED 亮多久 */

#define SERVO_PULSE_MIN  500u  /* 0°   的脉宽 */
#define SERVO_PULSE_MAX 2500u  /* 180° 的脉宽 */

#define ECHO_WAIT_MS   5u    /* 等 Echo 上升沿的超时 */
#define ECHO_MAX_US  25000u  /* Echo 高电平宽度上限（≈431cm），超过判无回波 */

/* ============================ 全局状态 ============================ */
static uint32_t g_trip_end   = 180u;  /* 这一趟扫到哪个角度为止：180 或 0 */
static uint32_t g_settle_end = 0u;    /* 舵机到位时刻（时间戳，不是"还要等多久"）*/
static uint32_t g_led_off_at = 0u;    /* LED 该灭的时刻；0 表示没在亮 */
static uint8_t  g_waiting    = 0u;    /* 1=正在等舵机到位 */

/* ============================================================================
 * 角度 → 脉宽（SG90 线性映射）
 * ----------------------------------------------------------------------------
 * 和仿真版 servo_set_angle() 里的那一行表达式一模一样。
 * 那句 180u 的钳位是保护舵机的机械限位，不是防溢出——
 * 脉宽一旦超过 2500µs，舵机会一直顶在 180° 的极限位置输出满力矩。
 * ==========================================================================*/
static uint32_t deg_to_pulse(uint32_t deg)
{
    if (deg > 180u) { deg = 180u; }
    return SERVO_PULSE_MIN + deg * (SERVO_PULSE_MAX - SERVO_PULSE_MIN) / 180u;
}

/* ============================================================================
 * 舵机转到 deg（真输出：写 TIM4->CCR1）
 * ----------------------------------------------------------------------------
 * 全题只 pwm_init() 一次、只用 TIM4_CH1 一个通道。
 * 改角度一律走 pwm_set_us()，它只动 CCR，不碰 PSC/ARR——
 * 因为 SG90 的控制周期必须恒定 20ms，周期一变舵机就数不准脉冲了。
 * CCR 的预装载（OC1PE）保证新脉宽在下一个周期边界统一生效，
 * 不会出现半长不短的畸形脉冲，那一下对舵机就是一次冲击。
 * ==========================================================================*/
static void servo_set_angle(uint32_t deg)
{
    pwm_set_us(TIM4_BASE, 1u, deg_to_pulse(deg));
}

/* ============================================================================
 * 扫描角度推进：这一趟走到头，就以同一个端点为起点反向开下一趟
 * ----------------------------------------------------------------------------
 * 这段是仿真版 main() 里那个双层循环的直译：
 *
 *     for (dir = 0; dir < 2; dir++) {          ← 外层：选方向和起点
 *         a = dir ? 180 : 0;                     ←   起点是上一趟的终点
 *         step = dir ? -5 : +5;                  ←   内层：往回走 / 往前走
 *         for (;;) { scan_step(a); if (a == 端点) break; a += step; }
 *     }
 *
 * 我没有用"g_dir = ±1 走到头就翻转"那种更简洁的写法，
 * 因为**折返点的重复上报是仿真版有意为之的**，不是 bug：
 *   上位机 watch_radar.py 里 leds_ok 校验的是
 *       sorted(leds[:6]) == [0, 0, 90, 90, 180, 180]
 *   也就是"去程闪 3 次 + 回程闪 3 次"，前提是**端点被报了两遍**：
 *   180° 是去程的终点又是回程的起点，0° 反之，两边各算一次。
 *   如果折返时直接跳到 175°，第一个往返的 LED 序列就变成
 *   [0,90,180,90,0,90]，这个校验直接过不了——所以这里老老实实重复一次。
 *
 * 另外方向用"这一趟的终点在 180 还是 0"来表达，
 * 就不用维护一个有正负的步长；真要写加减，
 * 必须用有符号类型（uint32_t 减到 0 以下会绕成巨大的正数，直接跳出量程）。
 * ==========================================================================*/
static uint32_t sweep_advance(uint32_t a)
{
    if (a == g_trip_end) {
        /* 到了这一趟的终点：新一趟的起点就是同一个角度（所以要重复报一次），
         * 然后把终点掉个头。 */
        uint32_t start = a;
        g_trip_end = (g_trip_end == 0u) ? 180u : 0u;
        return start;
    }
    /* 终点在 180 就说明这一趟是**往上**走（0→180），加步长；
     * 终点在 0 就是往下走（180→0），减步长。 */
    return (g_trip_end == 180u) ? (a + STEP_DEG) : (a - STEP_DEG);
}

/* ============================================================================
 * HC-SR04 测一次距离，返回毫米。0 = 无回波 / 超量程。
 * ----------------------------------------------------------------------------
 * 全函数所有等待都带超时，没有一处死等——
 * 这是"真板版比仿真版多出来的东西"：
 * 仿真里读 mailbox 永远立刻就有值，不存在传感器失联的情况；
 * 真板上一根线松了、模块没上电、或者探头朝着天花板，Echo 就一直不回来。
 * 死等的表现是"整机没有任何反应"：串口不出字、灯不闪、没有 HardFault，
 * 因为 CPU 就是老老实实在那儿转圈——这种 bug 最难查，所以从一开始就不留这条路。
 *
 * 用 DWT 量回波宽度而不是 delay_us()：delay_us 是"再等固定这么久"，
 * 测距要的是"刚才那段时间有多长"，必须读计数的差值。
 * DWT 是 Cortex-M4 内核自带的，不占任何定时器通道——
 * 所以 TIM4 可以整个留给舵机，不用为了测距再开一个 TIM。
 * ==========================================================================*/
static uint32_t hcsr04_read_mm(void)
{
    /* ① 给 Trig 一个 ≥10µs 高脉冲。
     * 先拉低再拉高：模块靠**上升沿**认"这是一次新触发"，
     * 上一次结束时若还停在高电平，这次就不算新触发，模块根本不会发射。 */
    gpio_write(PIN_TRIG, 0u);
    delay_us(5u);
    gpio_write(PIN_TRIG, 1u);
    delay_us(12u);              /* 手册要求 ≥10µs */
    gpio_write(PIN_TRIG, 0u);

    /* ② 等 Echo 上升沿（回波回来），带超时 */
    uint32_t t0 = millis();
    while (gpio_read(PIN_ECHO) == 0u) {
        if ((millis() - t0) >= ECHO_WAIT_MS) { return 0u; }
    }

    /* ③ 量 Echo 高电平宽度，超量程就判无回波 */
    uint32_t start = DWT_CYCCNT;
    uint32_t limit = (g_sysclk_hz / 1000000u) * ECHO_MAX_US;   /* 168×25000 = 420万 */

    while (gpio_read(PIN_ECHO) != 0u) {
        if ((DWT_CYCCNT - start) > limit) {
            /* 把这一声耗干净再返回，否则下一轮从一个还在高的 Echo 出发 */
            while (gpio_read(PIN_ECHO) != 0u) {
                if ((DWT_CYCCNT - start) > (limit * 2u)) { break; }
            }
            return 0u;
        }
    }

    /* ④ 距离 = 声波往返时间 ÷ 2 × 声速。
     * cm = us/58（343m/s = 34300cm/s，往返要除 2，已经折进 58 这个常数），
     * 所以 mm = us×1000/58。先乘后除是为了保住小数点后那一位：
     * 直接 (us/58)*10 会让 12.0cm 和 12.9cm 打成同一个数。
     * us 被 limit 卡在 25000 以内，25000×1000 装得进 32 位无符号，不会溢出。 */
    uint32_t us = (DWT_CYCCNT - start) / (g_sysclk_hz / 1000000u);
    return us * 1000u / 58u;
}

/* ============================================================================
 * 一个扫描步：测距 + 串口上报 + 关键角度打点
 * ----------------------------------------------------------------------------
 * 报文格式严格对齐 watch_radar.py 的正则，一个多余的字符都不能有：
 *     "45:12.3\r\n"          —— 角度:厘米.毫米位
 *     "[LED] angle=90\r\n"   —— 关键角度标记
 * ==========================================================================*/
static void scan_step(uint32_t angle)
{
    uint32_t mm = hcsr04_read_mm();

    /* 距离存的是整数毫米，要显示成 12.3cm 就得拆开：
     *   mm/10 = 整数厘米，mm%10 = 小数点后那一位。 */
    uart_putu(USART1_BASE, angle);
    uart_putc(USART1_BASE, ':');
    uart_putu(USART1_BASE, mm / 10u);
    uart_putc(USART1_BASE, '.');
    uart_putu(USART1_BASE, mm % 10u);
    uart_putc(USART1_BASE, '\r');
    uart_putc(USART1_BASE, '\n');

    /* 上位机看到的 "0.0" 表示"这个角度没收到回波"，
     * 不是"障碍物贴在 0cm"。会出现在扫到最左/最右（探头近乎侧向打掠）、
     * 目标超出 4m、或者角度正对着软材料（布、玻璃）的时候。
     * 格式上不能改成别的——watch_radar.py 的正则只认 \d+:\d+.\d 一种，
     * 改成 "45:--" 的话上位机会整行丢掉，连"这里没测到"都不知道。 */
    if (angle % 90u == 0u) {
        uart_puts(USART1_BASE, "[LED] angle=");
        uart_putu(USART1_BASE, angle);
        uart_puts(USART1_BASE, "\r\n");

        /* LED 亮 50ms。仿真版这里是 led_pulse(50) —— 一个阻塞的"亮-延时-灭"。
         * 真板版改成记一个"该灭的时刻"，由主循环去判：
         * 10ms 一闪的 LED 用阻塞延时去等，纯粹是在浪费 CPU，
         * 而且会让串口在这 50ms 内停顿，雷达点会掉几个。 */
        gpio_write(PIN_LED, 1u);
        g_led_off_at = millis() + LED_PULSE_MS;
    }
}

int main(void)
{
    /* ---- 时钟与时基 ---- */
    clock_init();
    dwt_init();                   /* delay_us + 量回波宽度都要用 */
    timer_ms_init();              /* TIM6 每 1ms 中断 → millis() 可用，整个扫描靠它 */

    /* ---- 调试串口 USART1 ----
     * 仿真版用 UART4，真板改 USART1（PA9/PA10），
     * 因为这题是"上位机实时收点画图"，PA9/PA10 在所有题里统一当调试口，
     * 换 USB-TTL 的位置时不用改代码。 */
    gpio_af(UART_TX, 7u);  gpio_mode(UART_TX, MODE_AF, PULL_UP, SPEED_HIGH);
    gpio_af(UART_RX, 7u);  gpio_mode(UART_RX, MODE_AF, PULL_UP, SPEED_HIGH);
    uart_init(USART1_BASE, g_pclk2_hz, 115200u);
    uart_puts(USART1_BASE, "\r\nQ10 radar (board) ready\r\n");
    uart_puts(USART1_BASE, "format: <angle>:<cm>.<mm>   e.g. 45:12.3\r\n");
    uart_puts(USART1_BASE, "ECHO(PB8) MUST be divided 5V->2.5V before connecting!\r\n");

    /* ---- 执行器上电摆到"不动作"的电平 ----
     * LED 先写低：gpio_out_init(pin, 1) 里 1 表示"高电平点亮"，
     * 它会先写相反电平，于是上电时 LED 是灭的，
     * 不会出现"一上电就闪一下"让人以为在报警。 */
    gpio_out_init(PIN_LED, 1u);

    /* ---- HC-SR04 Trig / Echo ----
     * Trig 上电先拉低，保证模块不会因为上电时脚上正好是高而误触发一次。
     * Echo 配下拉：正常时它是推挽输出、外部什么都不用加；
     * 但线松了/模块没上电时，浮空引脚的电平是随机的，
     * 测距会疯狂输出乱数，界面上表现为雷达图全是毛刺。
     * 配下拉之后，断线 = 一直读到低 = "永远无回波"，是一个安全的答案。 */
    gpio_out_init(PIN_TRIG, 1u);
    gpio_mode(PIN_ECHO, MODE_IN, PULL_DOWN, SPEED_LOW);

    /* ---- 舵机 PWM：TIM4_CH1 → PB6 ----
     * ★ 必须自己合 TIM4 的时钟闸：pwm_init() 只配寄存器不开 RCC。
     *   定时器时钟没开时，寄存器写不生效，输出脚上一个沿都不会有。
     *   APB1ENR 位序：bit0=TIM2 bit1=TIM3 bit2=TIM4。 */
    gpio_af(PIN_SERVO, 2u);                  /* PB6 复用为 TIM4_CH1 */
    gpio_mode(PIN_SERVO, MODE_AF, PULL_NONE, SPEED_HIGH);
    RCC_APB1ENR |= (1u << 2);                /* TIM4EN */

    /* ★ 全题只 pwm_init() 一次、只用 CH1 一个通道。
     *   PB7/PB8 虽然也是 TIM4 的 CH2/CH3，但它们在这里是普通 GPIO，
     *   复用功能是每个引脚独立的，不占通道。
     *   pwm_init 会重设 PSC/ARR，所以一旦周期被改坏（不再是 20ms），
     *   舵机就再也认不出位置了——后面调角度一律走 pwm_set_us()。 */
    pwm_init(TIM4_BASE, 1u, 20000u);          /* 20ms = 50Hz，SG90 的固定周期 */

    /* 上电先把舵机摆到 0°（SG90 的机械安全端点之一）再开始扫描。
     * 不要一上电就给 180°：舵机不知道自己停在哪，
     * 第一个脉冲就是极限角度的话，它会从随机位置猛甩过去，
     * 冲击电流容易把减速齿轮的齿和内部电位器滑片打坏。 */
    servo_set_angle(0u);
    delay_ms(300u);                          /* 上电阶段唯一一次 delay，
                                               让舵机有时间走到 0° 再开始扫。
                                               运行期一律用 millis()，绝不用 delay */

    uint32_t angle      = 0u;    /* 当前角度 */
    uint32_t next_step  = 0u;    /* 下一次"转角度"的时刻 */

    for (;;) {
        uint32_t now = millis();

        /* ---- LED 关灯：也是非阻塞的 ---- */
        if ((g_led_off_at != 0u) && ((int32_t)(now - g_led_off_at) >= 0)) {
            gpio_write(PIN_LED, 0u);
            g_led_off_at = 0u;
        }

        if (g_waiting != 0u) {
            /* ---- 阶段一：等舵机到位 ----
             * 这里只比较时间戳，不死等，所以主循环每一圈都还能回来。
             * 舵机从"刚收到新角度"到"机械停稳"需要时间，
             * 5° 的小角度大约 200ms。提前测的话探头还在半路上，
             * 量到的是转角过程中的乱距离。 */
            if ((int32_t)(now - g_settle_end) >= 0) {
                g_waiting = 0u;
                scan_step(angle);

                /* 测完马上可以转下一个角度。200ms 的间隔本来就已经
                 * 远大于 HC-SR04 要求的 60ms 发射间隔，不会读到上一次的回波。 */
                next_step = millis();
            }
        } else if ((int32_t)(now - next_step) >= 0) {
            /* ---- 阶段二：转到下一个角度，开始新的到位计时 ---- */
            servo_set_angle(angle);
            g_settle_end = millis() + STEP_DELAY_MS;
            g_waiting    = 1u;
            angle        = sweep_advance(angle);
        }

        /* 主循环其余时间是空的——但正因为是空的，
         * 以后想加"按键暂停扫描""串口下发指令改扫描速度"，
         * 只要在这里加一个分支即可，不用动任何 delay。 */
    }
}