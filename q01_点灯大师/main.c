/* ============================================================================
 * lesson3_q1_diandeng/main.c —— 笔试第1题「点灯大师」全仿真版（逐行注释）
 * ----------------------------------------------------------------------------
 * 题目要求：
 *   - 按键 A 按下：灯亮（红色）
 *   - 按键 B 按下：灯开始三种颜色循环闪烁（红→绿→蓝→红…）
 *   - 再次按按键 A：灯灭
 *
 * 硬件映射（用 Discovery 板的 4 个用户 LED 模拟一个三色 RGB 灯）：
 *   红色 = PD14   绿色 = PD12   蓝色 = PD15   （PD13 橙色不用）
 *   按键 A = PA0   按键 B = PA1   （按下=高电平，松开=低电平）
 *
 * 这题的三个新东西（L1/L2 没见过的）：
 *   1) GPIO 输入：读 IDR 寄存器，知道按键有没有按下（L1 是输出写 BSRR）
 *   2) 沿检测：只认"松开→按下"那一瞬间，按住不放不重复触发
 *   3) 状态机：用一个变量记录"现在是哪个模式"，按按键在模式间跳转
 * ==========================================================================*/

#include <stdint.h>   /* 提供 uint32_t 这种"固定32位无符号整数"类型 */

/* ----------------------------------------------------------------------------
 * MMIO 宏：把一个数字地址变成"可以读写的硬件寄存器"。
 *   (uint32_t *)(addr)  把整数地址转成"指向32位数的指针"
 *   *( ... )            取这个地址里的内容（左值，可读写）
 *   volatile            告诉编译器：别优化，每次都真的去读/写硬件
 * L1 就学过，这里再出现一次。
 * --------------------------------------------------------------------------*/
#define MMIO(addr) (*(volatile uint32_t *)(addr))

/* ============================================================================
 * 第一组寄存器：RCC 时钟（用任何外设前先给它上电）
 * ==========================================================================
 * RCC 基址 0x40023800，AHB1ENR 偏移 0x30，地址 = 0x40023830。
 * 这题同时用到 GPIOA（按键）和 GPIOD（灯），所以两个时钟都开。
 * --------------------------------------------------------------------------*/
#define RCC_AHB1ENR        MMIO(0x40023800u + 0x30u)  /* AHB1 外设时钟使能寄存器 */
#define RCC_AHB1ENR_GPIOA  (1u << 0)                  /* GPIOA 时钟位 = 第0位 */
#define RCC_AHB1ENR_GPIOD  (1u << 3)                  /* GPIOD 时钟位 = 第3位 */

/* ============================================================================
 * 第二组寄存器：GPIOA —— 按键输入（新东西！）
 * ==========================================================================
 * 【输入 vs 输出】
 *   L1 点灯是输出：我们写 BSRR/ODR，让引脚变高变低，灯跟着亮灭。
 *   这次是输入：外部的按键把引脚拉高/拉低，我们要"读"引脚现在是高还是低。
 *
 * 输入用的寄存器叫 IDR（Input Data Register），只读：
 *   读它的第 n 位 = 第 n 号引脚现在的电平（1=高，0=低）。
 * 仿真里按键是 watch_buttons.py 用 OnGPIO 把 PA0/PA1 拉高拉低，
 * 固件读 IDR 就能感知到，和真按键一模一样。
 * --------------------------------------------------------------------------*/
#define GPIOA_MODER  MMIO(0x40020000u + 0x00u)  /* 方向寄存器：每脚2位，00=输入 */
#define GPIOA_IDR    MMIO(0x40020000u + 0x10u)  /* 输入数据寄存器（只读） */
#define BTN_A  (1u << 0)   /* 第0位 = PA0 = 按键 A */
#define BTN_B  (1u << 1)   /* 第1位 = PA1 = 按键 B */

/* ============================================================================
 * 第三组寄存器：GPIOD —— LED 输出（和 L1 完全一样的套路）
 * ==========================================================================
 * BSRR 是 32 位"只写扳机"：
 *   低 16 位写 1 -> 对应引脚拉高（亮）
 *   高 16 位写 1 -> 对应引脚拉低（灭），引脚 n 的复位位在第 n+16 位
 * 写 0 的位什么都不做。
 * --------------------------------------------------------------------------*/
#define GPIOD_MODER  MMIO(0x40020C00u + 0x00u)  /* 方向寄存器 */
#define GPIOD_BSRR   MMIO(0x40020C00u + 0x18u)  /* 置位/复位寄存器 */
#define LED_RED    (1u << 14)   /* PD14 红，低16位置位位 */
#define LED_GREEN  (1u << 12)   /* PD12 绿 */
#define LED_BLUE   (1u << 15)   /* PD15 蓝 */
/* ALL_OFF = 三个灯的"复位位"拼起来，写一次就能同时灭掉三个灯：
 *   红复位 = 1<<(14+16) = 1<<30
 *   绿复位 = 1<<(12+16) = 1<<28
 *   蓝复位 = 1<<(15+16) = 1<<31  */
#define ALL_OFF  ((1u << (14u+16u)) | (1u << (12u+16u)) | (1u << (15u+16u)))

/* ============================================================================
 * 状态机：用一个"枚举"类型定义所有可能的状态
 * ==========================================================================
 * 枚举就是给一组整数起名字，让代码读起来像人话：
 *   ST_OFF=0  全灭
 *   ST_RED=1  红色常亮
 *   ST_CYCLE=2  红→绿→蓝 循环
 * 用一个 state_t 变量记住"现在处于哪个状态"，再根据按键在状态间跳。
 * --------------------------------------------------------------------------*/
typedef enum {
    ST_OFF,     /* 0：全灭 */
    ST_RED,     /* 1：红色常亮 */
    ST_CYCLE    /* 2：三色循环 */
} state_t;

/* ================= 启动代码（和 L1/L2 完全相同，先照抄、略过细节） =================
 * 作用：上电后设栈指针、把 .data 从 Flash 拷到 RAM、把 .bss 清零，然后调用 main。
 * 你现在只需要知道：main() 是从这里被调用的。 */
extern uint32_t _estack, _sidata, _sdata, _edata, _sbss, _ebss;
typedef void (*isr_t)(void);
void Reset_Handler(void);
void Default_Handler(void);
int  main(void);
__attribute__((section(".isr_vector"), used))
isr_t vector_table[16] = {
    (isr_t)&_estack, Reset_Handler,
    Default_Handler, Default_Handler, Default_Handler, Default_Handler,
    Default_Handler, 0, 0, 0, 0, Default_Handler, Default_Handler,
    0, Default_Handler, Default_Handler,
};
__attribute__((naked))
void Reset_Handler(void)
{
    __asm volatile ("ldr r0, =_estack\n\t" "mov sp, r0\n\t" : : : "r0");
    for (uint32_t *p = &_sdata, *s = &_sidata; p < &_edata;) *p++ = *s++;
    for (uint32_t *p = &_sbss; p < &_ebss;) *p++ = 0;
    (void)main();
    for (;;) ;
}
void Default_Handler(void) { for (;;) ; }

/* ================= 用户代码从这里开始（重点读这一段） ================= */

/* 简单忙等待：空转 n 圈拖时间（和 L1/L2 一样）。
 * volatile 防止编译器把这个"看似没用"的循环优化掉。 */
static void delay(volatile uint32_t n)
{
    while (n--)              /* n 从传入值开始每次减1，减到0退出 */
        __asm__("nop");      /* nop = 空操作指令，占一个周期拖时间 */
}

/* ----------------------------------------------------------------------------
 * show_color：只亮指定颜色，其它灭掉
 *   idx=0 红，idx=1 绿，idx=2 蓝
 * 做法分两步：
 *   1) 写 ALL_OFF 到 BSRR 高16位 -> 三个灯全部复位(灭)
 *   2) 写对应灯的位置到 BSRR 低16位 -> 把那一个灯置位(亮)
 * 因为 BSRR 写0的位什么都不做，所以两步互不干扰。
 * --------------------------------------------------------------------------*/
static void show_color(uint32_t idx)
{
    GPIOD_BSRR = ALL_OFF;              /* 第一步：全灭 */
    if (idx == 0u)      GPIOD_BSRR = LED_RED;    /* 第二步：亮红 */
    else if (idx == 1u) GPIOD_BSRR = LED_GREEN;  /* 第二步：亮绿 */
    else                GPIOD_BSRR = LED_BLUE;   /* 第二步：亮蓝 */
}

/* ----------------------------------------------------------------------------
 * main：程序入口
 * --------------------------------------------------------------------------*/
int main(void)
{
    /* ==================== 初始化部分（只跑一次） ==================== */

    /* 1) 开 GPIOA 和 GPIOD 的时钟。
     *    用 |= 是因为这个寄存器还管着别的外设，我们只想把这两位置1，其它位不动。 */
    RCC_AHB1ENR |= RCC_AHB1ENR_GPIOA | RCC_AHB1ENR_GPIOD;

    /* 2) 把 PA0、PA1 配成输入。
     *    MODER 每个引脚占 2 位：00=输入，01=输出。
     *    PA0 占位0-1，PA1 占位2-3。
     *    ~((3<<0)|(3<<2)) 是把这4位先变成0、其它位全1，再 & 上去就只清这4位。
     *    复位默认就是00(输入)，这里显式清一下更稳妥。 */
    GPIOA_MODER &= ~((3u << 0) | (3u << 2));

    /* 3) 把 PD12、PD14、PD15 配成输出（01）。
     *    PD12 占位24-25，PD14 占位28-29，PD15 占位30-31。
     *    先 & ~(...) 把这6位清0，再 | (1<<...) 把每对的低位设成1 -> 01。 */
    GPIOD_MODER = (GPIOD_MODER & ~((3u << 24) | (3u << 28) | (3u << 30)))
                | (1u << 24) | (1u << 28) | (1u << 30);

    /* 4) 初始状态：三个灯全灭。 */
    GPIOD_BSRR = ALL_OFF;

    /* ==================== 状态机变量 ==================== */
    state_t  state = ST_OFF;          /* 当前状态，开机从"全灭"开始 */
    uint32_t cycle_idx = 0u;          /* CYCLE状态下当前亮的颜色：0红1绿2蓝 */
    uint32_t cycle_ticks = 0u;        /* CYCLE状态下的换色计时器（数采样周期数） */
    uint32_t prev_a = 0u;             /* 上一圈采样到的按键A电平，用于沿检测 */
    uint32_t prev_b = 0u;             /* 上一圈采样到的按键B电平 */

    /* ==================== 主循环（永远跑下去） ====================
     * 每一圈做三件事：读按键 -> 沿检测 -> 根据当前状态响应 */
    for (;;) {

        /* ---- 第一步：读按键 ----
         * 读一次 IDR 拿到 PA0/PA1 当前电平，用 & 屏蔽出对应位，
         * 非0就是1(按下)，0就是0(松开)。 */
        uint32_t idr = GPIOA_IDR;                       /* 读输入寄存器 */
        uint32_t a = (idr & BTN_A) ? 1u : 0u;           /* 按键A：1=按下 0=松开 */
        uint32_t b = (idr & BTN_B) ? 1u : 0u;           /* 按键B */

        /* ---- 第二步：沿检测（这题最关键的新技能） ----
         * 我们只想要"刚按下的那一瞬间"触发一次，按住不放不能重复触发。
         *
         * 原理：记住上一圈的电平 prev_a，和这一圈的 a 比：
         *   a=1 且 prev_a=0  ->  上一圈松开、这一圈按下 = 上升沿 = 刚按下 ✅
         *   a=1 且 prev_a=1  ->  按住中，不触发
         *   a=0              ->  松开，不触发
         *
         * 时间线举例（按键在第3圈按下、第6圈松开）：
         *   圈数:  1  2  3  4  5  6  7
         *   a:     0  0  1  1  1  0  0
         *   prev:  0  0  0  1  1  1  0
         *   press: 0  0  1  0  0  0  0   <- 只有第3圈触发一次
         *
         * 注意顺序：必须先用旧的 prev_a 算出 a_press，再更新 prev_a=a。
         * 如果先更新，prev 永远等于 a，就永远检测不到沿了。 */
        uint32_t a_press = (a && !prev_a) ? 1u : 0u;   /* A的上升沿 */
        uint32_t b_press = (b && !prev_b) ? 1u : 0u;   /* B的上升沿 */
        prev_a = a;    /* 存起来，下一圈当"上次"用 */
        prev_b = b;

        /* ---- 第三步：根据当前状态决定做什么（状态机核心） ---- */
        switch (state) {

        /* 状态1：全灭。只响应按键A -> 变红常亮 */
        case ST_OFF:
            if (a_press) {              /* 检测到A按下 */
                state = ST_RED;         /* 跳到"红色常亮"状态 */
                show_color(0u);         /* 亮红色 */
            }
            break;                      /* switch 的每个 case 必须 break，否则会继续往下跑 */

        /* 状态2：红色常亮。按A -> 熄灭；按B -> 进入三色循环 */
        case ST_RED:
            if (a_press) {              /* A按下 -> 熄灭 */
                state = ST_OFF;         /* 跳回全灭状态 */
                GPIOD_BSRR = ALL_OFF;   /* 灯全灭 */
            } else if (b_press) {       /* B按下 -> 进入循环 */
                state = ST_CYCLE;       /* 跳到循环状态 */
                cycle_idx = 0u;         /* 从红色开始 */
                cycle_ticks = 0u;       /* 换色计时器清零 */
                show_color(0u);         /* 先亮红色 */
            }
            break;

        /* 状态3：三色循环。按A -> 熄灭；否则自动每8圈换一个颜色 */
        case ST_CYCLE:
            if (a_press) {              /* A按下 -> 熄灭，退出循环 */
                state = ST_OFF;
                GPIOD_BSRR = ALL_OFF;
            } else {
                /* 没按键时：每过8个采样周期换一次色。
                 * 一圈约25ms，8圈约200ms，所以每种颜色亮200ms。
                 * 这种"数圈数而不是用阻塞delay"的写法叫非阻塞，
                 * 好处是换色期间按键依然能及时响应。 */
                cycle_ticks++;                       /* 计时+1 */
                if (cycle_ticks >= 8u) {             /* 满8圈了 */
                    cycle_ticks = 0u;                /* 计时器清零 */
                    cycle_idx = (cycle_idx + 1u) % 3u;  /* 0->1->2->0 循环 */
                    show_color(cycle_idx);           /* 亮新颜色 */
                }
            }
            break;
        }

        /* ---- 每圈末尾：等约25ms再采样下一次 ----
         * 两个作用：
         *   1) 消抖：真按键按下瞬间金属片会颤几ms，隔25ms采一次就跳过了抖动；
         *   2) 给状态机一个稳定的节奏，cycle_ticks 数的就是这个节奏。
         * 仿真里按键是干净的不抖，但这个习惯上真板必须有。 */
        delay(20000);
    }
}
