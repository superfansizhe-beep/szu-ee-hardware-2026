/* ============================================================================
 * lesson1_blink_f407/main.c —— L1 点灯（STM32F407，在 Renode 里仿真）
 * ----------------------------------------------------------------------------
 * 这个文件做的事，一句话：让 PD13（Discovery 板的橙色灯）不断亮、灭。
 *
 * 和常见教程的区别：这里【没有用 HAL 库、没有操作系统、没有 Keil/CubeMX】，
 * 全部是直接读写芯片手册规定的寄存器地址，也就是“裸机 / 直接操作寄存器”。
 *
 * 读这份代码的主线（先记住这 4 步，细节往下看）：
 *   1) 开时钟：外设默认是断电的，先在 RCC 里给 GPIOD 上电；
 *   2) 配方向：在 MODER 里把 PD13 这两个位设成“输出”；
 *   3) 输出电平：往 BSRR 写特定的位，把 PD13 拉高(亮)/拉低(灭)；
 *   4) 我们在电脑上用 Python 读 ODR 寄存器，确认引脚电平真的在变。
 *
 * 涉及的 4 个寄存器（F407 / GPIOD，地址先混个眼熟，下面逐个解释）：
 *   RCC_AHB1ENR @0x40023830  外设时钟开关（总闸门）
 *   GPIOD_MODER  @0x40020C00  每个引脚的方向（输入/输出）
 *   GPIOD_ODR    @0x40020C14  每个引脚“现在是高还是低”（读它看灯）
 *   GPIOD_BSRR   @0x40020C18  写它可以一次性把某脚拉高/拉低（点灯用它）
 * ==========================================================================*/

/* stdint.h 是编译器自带的一个头文件（不是操作系统的东西），它提供
 * uint32_t 这种“宽度固定”的类型：uint32_t 一定是无符号 32 位整数。
 * 操作硬件寄存器必须用固定宽度，否则换编译器/平台位数会出错。
 * 注意：我们能用这个头文件，不代表链接了标准库；编译时用的是 -nostdlib，
 * 头文件(声明) 和 库(实现) 是两回事。 */
#include <stdint.h>

/* ----------------------------------------------------------------------------
 * 最核心的一个宏：把一个“数字地址”变成可以读写的“硬件寄存器”。
 *
 *   #define MMIO(addr) (*(volatile uint32_t *)(addr))
 *
 * 从里往外拆：
 *   (uint32_t *)(addr)  —— 把整数 addr 强制转换成“指向 32 位无符号数的指针”；
 *   *( ... )            —— 指针前面加 * 表示“这个地址里装的内容”，是个左值，
 *                          对它赋值就是往该地址【写】，取它的值就是从该地址【读】；
 *   volatile            —— 关键字，告诉编译器：“这块内存你别自作主张优化”，
 *                          每次读都真的去读、每次写都真的去写。因为硬件寄存器
 *                          会在程序看不见的情况下被硬件改变，或者写入本身就有
 *                          副作用（比如写 BSRR 会改变电平）。
 *
 * 背景概念“内存映射 I/O(MMIO)”：Cortex-M 没有专门的 IN/OUT 指令，外设的寄存器
 * 就“长”在固定的内存地址上，像访问普通内存一样读写这些地址，就是在操控硬件。
 *
 * 于是  MMIO(0x40020C14)  你可以直接理解成“位于 0x40020C14 的那个 32 位寄存器”。
 * --------------------------------------------------------------------------*/
#define MMIO(addr) (*(volatile uint32_t *)(addr))

/* ---- GPIOD 这组引脚的寄存器 ------------------------------------------------
 * 一个 GPIO 外设占一段地址，叫“基址”；组内每个寄存器再加一个“偏移量”。
 * GPIOD 基址 = 0x40020C00。
 *   数字末尾的 u 表示 unsigned（无符号整数），避免移位时出现有符号数的坑。
 *
 * RCC = Reset and Clock Control，复位与时钟控制单元，是所有外设的“电闸房”。
 *   RCC_AHB1ENR = RCC 基址 0x40023800 + 偏移 0x30 = 0x40023830
 *   名字里 EN = Enable（使能/开关），AHB1 是这条总线的名字。
 *---------------------------------------------------------------------------*/
#define RCC_AHB1ENR MMIO(0x40023800u + 0x30u) /* 外设时钟使能寄存器（电闸） */
#define GPIOD_MODER MMIO(0x40020C00u + 0x00u) /* MODER：方向，偏移 0x00 */
#define GPIOD_ODR   MMIO(0x40020C00u + 0x14u) /* ODR：输出电平，偏移 0x14 */
#define GPIOD_BSRR  MMIO(0x40020C00u + 0x18u) /* BSRR：置位/复位，偏移 0x18 */

/* RCC_AHB1ENR 的第 3 位对应 GPIOD 这组的时钟（每组一个位，查手册得到）。
 * 1u << 3 就是把 1 左移 3 位，得到二进制 ...00001000 = 0x08。
 * 把这一位写成 1 = 给 GPIOD 供时钟；写成 0 = 断电。 */
#define RCC_AHB1ENR_GPIOD (1u << 3)  /* GPIOD 时钟使能位 = 第 3 位 */

/* 我们要点的引脚编号：PD13 = GPIOD 组的第 13 号脚（橙色灯）。
 * 想改成绿灯就把 13 换成 12，下面所有公式会自动跟着变——这就是用宏的好处。 */
#define LED_PIN           13u

/* BSRR 是 32 位、被劈成两半的“只写扳机”寄存器：
 *   低 16 位(BS)：往第 n 位写 1 -> 把引脚 n 拉高（置位，灯亮）；
 *   高 16 位(BR)：往第 n+16 位写 1 -> 把引脚 n 拉低（复位，灯灭）。
 * 所以同一个脚 n：拉高写 1<<n，拉低写 1<<(n+16)，“+16”就是跳到高那一半。
 *   PD13：LED_SET   = 1<<13 = 0x00002000
 *         LED_RESET = 1<<29 = 0x20000000
 * 写 0 的位什么都不做，因此不会误伤别的脚；而且一次写就生效，不会被中断打断。*/
#define LED_SET           (1u << LED_PIN)          /* 拉高=亮（低16位区） */
#define LED_RESET         (1u << (LED_PIN + 16u))  /* 拉低=灭（高16位区） */

/* ============================================================================
 * 下面这一整段是“最小启动代码”。现在阶段你【先看懂大意、能照抄】即可，
 * L2/L3 用到中断时还会回来细讲。它解决一个问题：芯片上电后，在调用 main()
 * 之前，C 程序运行所需要的环境（栈、已初始化变量、清零变量）得先准备好。
 * ==========================================================================*/

/* 这些下划线开头的符号（_estack 等）不是普通 C 变量，它们的“地址/数值”是由
 * 链接脚本 stm32f407.ld 规定的（栈顶、各数据段的起止）。用 extern 声明一下，
 * 告诉编译器“这些名字在别处定义”，这里只引用它们的地址。 */
extern uint32_t _estack, _sidata, _sdata, _edata, _sbss, _ebss;

/* 定义一个类型 isr_t：“指向一个无参数、无返回值函数的指针”。
 * 中断/异常处理函数就是这种形状，向量表里装的就是一串这种函数指针。 */
typedef void (*isr_t)(void);

void Reset_Handler(void);   /* 复位函数：上电后第一个执行的 C/汇编函数 */
void Default_Handler(void); /* 默认异常处理：啥也不做，原地死循环 */
int  main(void);            /* 我们的主函数，在启动代码最后被调用 */

/* 向量表：一个函数指针数组，放到名为 ".isr_vector" 的专门段里。
 *   __attribute__((section(".isr_vector"))) ：把这张表放进 .isr_vector 段，
 *       链接脚本会把该段摆在 Flash 最开头 0x08000000——芯片上电固定从这里读；
 *   used ：告诉编译器“即使看起来没人用，也别把它优化删掉”。
 *
 * Cortex-M 硬件规定这张表的头两项非常特殊：
 *   [0] 初始栈指针 SP 的值（这里放链接脚本给的栈顶 _estack=0x20020000）；
 *   [1] “复位处理函数”的地址（上电/复位后 CPU 从这里开始取指令）。
 * 其余项是各种异常/中断，我们暂时都指向 Default_Handler（用 0 表示没有处理）。*/
__attribute__((section(".isr_vector"), used))
isr_t vector_table[16] = {
    (isr_t)&_estack,   /* 0: 初始栈指针（取 _estack 的“地址值”当 SP） */
    Reset_Handler,     /* 1: 复位后第一个跑的函数 */
    Default_Handler, Default_Handler, Default_Handler, Default_Handler,
    Default_Handler, 0, 0, 0, 0, Default_Handler, Default_Handler,
    0, Default_Handler, Default_Handler,
};

/* Reset_Handler：复位入口。
 * naked 属性表示“不要编译器自动加进出场指令”，因为此时栈还没设好。 */
__attribute__((naked))
void Reset_Handler(void)
{
    /* 第一步：把栈指针 SP 设为链接脚本规定的栈顶 _estack。
     * 这是两句汇编：ldr 取 _estack 的地址到 r0，mov 把它写入 sp。 */
    __asm volatile ("ldr r0, =_estack\n\t"
                    "mov sp, r0\n\t"
                    : : : "r0");          /* "r0" 告诉编译器 r0 被我们用了 */

    /* 第二步：搬运 .data 段。C 里“带初值的全局变量”初值存在 Flash，
     * 但运行时要在 RAM 里能改，所以把初值从 Flash(_sidata) 拷到
     * RAM 的 _sdata.._edata 区间。本程序没有这类变量，这段相当于空跑。 */
    for (uint32_t *p = &_sdata, *s = &_sidata; p < &_edata;)
        *p++ = *s++;                 /* 从 Flash 读一个字，写到 RAM，指针各 +1 */

    /* 第三步：把 .bss 段清零。C 规定“没给初值的全局/静态变量”初值必须是 0。 */
    for (uint32_t *p = &_sbss; p < &_ebss;)
        *p++ = 0;

    /* 第四步：环境就绪，调用 main()。前面加 (void) 表示“故意不用返回值”。 */
    (void)main();

    for (;;) ;                       /* 保险：main 正常不会返回，万一返回就停在这 */
}

/* 其他所有异常/中断的兜底处理：原地死循环（真板上常用来暴露“程序跑飞了”）。 */
void Default_Handler(void) { for (;;) ; }

/* ============================================================================
 * ===================== 用户代码从这里开始 ===================================
 * ==========================================================================*/

/* 最简单的“忙等待”延时：什么都不干，就空转 n 圈来消耗时间。
 * 参数加 volatile 是防止编译器发现“这个循环没意义”而把它整个优化掉。
 * nop = No Operation，一条什么也不做、但确实占用一个指令周期的汇编指令。
 * 注意：这种延时不精确（圈数随编译结果/主频变化），L3 会换成精准的 SysTick。
 * 在 Renode 里它消耗的是“虚拟时间”，所以我们能看到灯按节奏闪。 */
static void delay(volatile uint32_t n)
{
    while (n--) {            /* n 每次减 1，减到 0 退出 */
        __asm__("nop");      /* 空操作，纯粹拖时间 */
    }
}

int main(void)
{
    /* ---- 第 1 步：打开 GPIOD 的时钟 -------------------------------------
     * |= 是“读-改-写”：先读出该寄存器当前值，只把第 3 位 OR 成 1，
     * 其它位原样保留（其它外设的开关位不能被我们顺手清掉）。
     * 对比：如果写 RCC_AHB1ENR = 0x08; 就会把其它位全清 0，可能关掉别的外设。
     * 真芯片上不写这行，GPIOD 断电，后面所有写 GPIO 的操作都无效（灯不亮）；
     * 这版 Renode 的 GPIO 模型没做“时钟门控”，所以仿真里不写也能闪——以真芯片为准。 */
    RCC_AHB1ENR |= RCC_AHB1ENR_GPIOD;

    /* ---- 第 2 步：把 PD13 配成“通用输出” --------------------------------
     * MODER 给【每个引脚留 2 个 bit】来选方向：
     *     00=输入(复位默认)  01=通用输出  10=复用功能  11=模拟
     * 引脚 n 占用的是第 2n 和 2n+1 位。PD13 -> 第 26、27 位（PD12 是 24、25）。
     *
     * 表达式拆解（标准的“先清后设”套路）：
     *   3u << 26            3 = 二进制 11，左移 26 位 => 只有第 26、27 位是 11；
     *   ~(3u << 26)         按位取反 => 这两位变 00、其余位全 1；
     *   GPIOD_MODER & ~(..) 与操作 => 把第 26、27 位【清成 00】，其它位不动；
     *   | (1u << 26)        再把第 26 位设 1、27 位保持 0 => 这两位 = 01(输出)。 */
    GPIOD_MODER = (GPIOD_MODER & ~(3u << 26)) | (1u << 26);

    /* ---- 第 3 步：无限循环，反复拉高、拉低 PD13 --------------------------
     * for(;;) 是 C 里“永远循环”的写法（没有条件，等价于 while(1)）。 */
    for (;;) {
        GPIOD_BSRR = LED_SET;     /* 往 BSRR 低区写 bit13：PD13 变高电平，灯亮 */
        delay(100000);            /* 保持亮，空转约 10 万圈（短） */
        GPIOD_BSRR = LED_RESET;   /* 往 BSRR 高区写 bit29：PD13 变低电平，灯灭 */
        delay(300000);            /* 保持灭，空转约 30 万圈（长）=> 短亮长灭 */
    }

    /* 小补充：本文件【从不直接写 ODR】。ODR 是“结果/状态”，由硬件在我们写
     * BSRR 时自动更新；我们在电脑端用 Python 读 ODR 的第 13 位来观察灯。
     * BSRR 是只写的命令，读完没有意义——所以“控制写 BSRR、观察读 ODR”。 */
}
