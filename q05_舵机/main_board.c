/* ============================================================================
 * q05_舵机/main_board.c —— 第五题「指哪打哪」真板版
 * ----------------------------------------------------------------------------
 * 【和仿真版 main.c 的关系】
 *   deg_to_pulse() 这个核心换算式一个字符没动，仿真版和真板版可以并排贴出来看：
 *       pulse_us = 500 + deg * 2000 / 180      ← 两边完全一样
 *   只把两头接到真硬件：
 *       仿真：目标角度由 Python 写 mailbox 0x2001FF00 → 真板：adc_read(PA0) 采电位器
 *       仿真：算出的脉宽写 mailbox 给 Python 看     → 真板：写 TIM4->CCR1 真实输出
 *
 *   【和仿真版不一样的两处，都是机械安全考虑，不是逻辑改动】
 *     ① 上电初始脉宽从仿真版的 0°(500µs) 改成**中位 90°(1500µs)**。
 *     ② 开机后先在中位停 300ms，再开始跟随电位器。
 *     原因见下面 sg90_safe_init() 的注释。
 *
 * ------------------------------------------------------------------
 * 一、SG90 的脉宽协议（舵机不是"给电压调角度"，是"给脉宽报位置"）
 * ------------------------------------------------------------------
 *   控制信号是**周期固定的脉冲串**，周期必须 20ms（50Hz）：
 *     周期里只有开头一小段是高电平，高电平的**宽度**才表示角度。
 *       高 500µs  → 0°
 *       高 1500µs → 90°（中位，也是厂家标定基准）
 *       高 2500µs → 180°
 *     所以线性公式就是 pulse_us = 500 + deg * 2000 / 180。
 *
 *   三个硬件层面的后果，考试很爱追问：
 *     ① 周期必须是 20ms 而不是"随便多少"。
 *        舵机内部是一个接收机 + 位置比较器，它靠**数脉冲**来判断位置。
 *        周期一变，它数的节拍就对不上，轻则角度不准，重则直接抖动不回中。
 *        所以下面 pwm_init() 用的是 20000µs，而且**全题只调一次**。
 *     ② 脉宽低于 500µs 或高于 2500µs，舵机会顶到机械限位。
 *        顶住之后它不会停，而是继续输出力矩去顶——堵转电流可达额定电流数倍，
 *        长时间顶住会烧舵机内部电位器/齿轮，或者把连杆机构顶变形。
 *        所以 deg_to_pulse() 里有 180° 的钳位，这不是"防止溢出"，是保护机构。
 *     ③ **上电第一个脉冲特别危险**。舵机上电时不知道自己停在哪（可能停在任意角度，
 *        也可能被人手动掰过），如果第一个脉冲就给 2500µs(180°)，
 *        它会从当前未知位置**猛甩到 180°**。角度跨度越大，冲击电流越大，
 *        传动齿和电位器滑片都容易被这一次甩坏。所以先归中。
 *
 * ------------------------------------------------------------------
 * 二、接线表（换板子只改下面这段 #define）
 * ------------------------------------------------------------------
 *   PB6 (TIM4_CH1, AF2) ── SG90 的信号线（通常是橙/白/黄那根）
 *        ⚠ SG90 自己的电源线（红色）要接**独立的 5V**，不要从 F407 的 3.3V 取。
 *          舵机堵转/启动瞬间电流能到几百 mA，3.3V 稳压器根本扛不住，
 *          表现出来是"舵机一动整块板子就复位"。GND 必须和 STM32 共地。
 *
 *   10kΩ 电位器（旋转式，带 3 个脚）分压：
 *        3.3V ──┬── 固定端 1 脚
 *              └── 滑片（中间那个脚）── PA0 (ADC1_IN0)   ← 这才是接单片机的那根
 *             GND ──┬── 固定端 3 脚
 *              └──
 *        接反了（3.3V 和 GND 对调）不会烧，只是电位器转到头时读数会在 0 和 4095
 *        之间跳变，表现为"电位器猛转时舵机猛甩"。和舵机猛甩是同一个现象，
 *        但根因完全不同，现场对着量一下就知道。
 *
 *   PA9 (USART1_TX, AF7) ── USB-TTL 的 RXD      115200-8-N-1
 *   PA10(USART1_RX, AF7) ── USB-TTL 的 TXD
 *
 * ------------------------------------------------------------------
 * 三、电位器行程 → 角度的映射（这里有个需要讲清楚的设计选择）
 * ------------------------------------------------------------------
 *   常见的 10kΩ 旋转电位器是 **270°** 行程，而 SG90 只有 180°。
 *   两种映射方式：
 *     (a) 4095 → -45°~225°：量程用满了，但两端超出舵机量程，
 *         会顶到机械限位。**绝对不能用**，理由见上面②。
 *     (b) 4095 → 0°~180°：电位器一圈到底全程可用，舵机永远不出量程。
 *
 *   我选 (b)。理由有两条：
 *     ① **安全**：舵机的机械行程是硬约束，映射关系绝不能把它顶出去。
 *        这条是决定性的——无论手感多好，顶限位都是不可接受的。
 *     ② **分辨率反而更好**：270° 的圈比 180° 的圈长，同样的手部动作
 *        在 270° 圈上对应的舵机角度变化更小，也就是说舵机角度的调节更"细"。
 *        换句话说，把整个电位器行程都用上（而不是只用中间 2/3），
 *        单圈能覆盖的 180° 角度变化更大，手感更"跟手"。
 *        量化到 12 位 ADC 是 4096 级，远超肉眼分辨不到的角度分辨率，
 *        所以 270° 行程相比 180° 行程带来的额外分辨率不是瓶颈。
 *
 *   还有一个真实硬件的细节：10kΩ 电位器接 3.3V 时，满量程电压只有 3.3V，
 *   而 F407 的 ADC 参考电压 VREF+ 通常接的就是 3.3V——正好压满量程。
 *   分压电阻不用另外加，电位器本身就是分压器。
 * ==========================================================================*/

#include "stm32f4_common.h"

/* ============================ 引脚表 ============================
 * 换板子/换接线只改这一段。下面代码一行都不用动。 */
#define PIN_SIG     PB6    /* TIM4_CH1, AF2 → SG90 信号线 */
#define PIN_POT     PA0    /* ADC1_IN0 → 电位器滑片         */
#define UART_TX     PA9    /* USART1_TX, AF7                */
#define UART_RX     PA10   /* USART1_RX, AF7                */

/* ============================ SG90 参数 ============================ */
#define SERVO_PERIOD   20000u  /* PWM 周期 20000µs = 20ms = 50Hz。
                                  舵机靠数脉冲认位置，周期错了角度就不准，
                                  所以这个值一次定死，全题不许再改 */
#define SERVO_PULSE_MIN   500u /* 0°   对应的脉宽 */
#define SERVO_PULSE_MID  1500u /* 90°  中位 */
#define SERVO_PULSE_MAX  2500u /* 180° 对应的脉宽 */
#define SERVO_CENTER_HOLD 300u /* 上电后在中位停留多久。
                                  舵机从"上电随机停的位置"转到中位需要一点时间，
                                  刚合上电就立刻让它跳到电位器指的位置，
                                  等于把省掉的那次大角度甩动换了个地方发生，
                                  一样会冲击机构。300ms 是实测够用的经验值 */

/* ============================ 可调参数 ============================ */
#define ADC_AVG      16u    /* 电位器 ADC 取 16 次平均。电位器滑片接触电阻不理想，
                              单次读数会在末尾几十个 LSB 里抖，直接用会让舵机
                              在目标角度上"丝丝发抖" */
#define PRINT_MS     200u   /* 每 200ms 打一次当前角度，方便现场对照读数 */

#define ADC_MAX      4095u  /* 12 位 ADC 满量程 */

/* ============================ 全局状态 ============================ */
static uint32_t g_last_print = 0u;

/* ============================================================================
 * 角度 → 脉宽（SG90 线性映射）
 * ----------------------------------------------------------------------------
 * 这段和仿真版 main.c 的 deg_to_pulse() 完全一样，连注释的口气都一致：
 * 因为这就是 SG90 的硬件协议，不是我发明的逻辑。
 *
 * 那个 180u 的钳位不能省：它是把"用户写超范围的角度"挡在舵机机械限位之外的最后一道。
 * 越界之后的脉宽会 >2500µs 或算成负数，
 * 前者顶坏舵机，后者会让定时器 CCR 变成一个巨大的无符号数，
 * 占空比直接冲到 100%，反而变成"持续高电平"——对舵机来说等于一直顶在 180°。
 * ==========================================================================*/
static uint32_t deg_to_pulse(uint32_t deg)
{
    if (deg > 180u) { deg = 180u; }
    return SERVO_PULSE_MIN + deg * (SERVO_PULSE_MAX - SERVO_PULSE_MIN) / 180u;
}

/* ============================================================================
 * ADC 原始值 → 角度（0~4095 映射到 0~180°，理由见文件头第三节）
 * ==========================================================================*/
static uint32_t adc_to_deg(uint32_t adc)
{
    if (adc > ADC_MAX) { adc = ADC_MAX; }

    /* 先乘后除，避免 adc/4095 在整数除法里直接塌成 0（4095/4095=1 时
     * 前面的乘法还没做，小量程分辨率就白扔了）。180*4095 只有 73 万多，
     * 32 位无符号装得下，不会溢出。 */
    uint32_t deg = adc * 180u / ADC_MAX;
    if (deg > 180u) { deg = 180u; }     /*  adc=4095 时正好 180，这句是防御性钳位 */
    return deg;
}

/* ============================================================================
 * 把舵机摆到中位并等它稳住
 * ----------------------------------------------------------------------------
 * 这是真板版和仿真版唯一"故意不一样"的地方。
 *
 * 仿真版开机就把 mailbox 写成 deg_to_pulse(0)，无所谓——那只是一堆数字，
 * 后面接的是 Python。真板后面接的是**有质量的机械结构**：
 * 舵机一上电，输出轴停在哪是不确定的（上次断电时停在哪、或者被人手动掰过），
 * 舵机只能靠收到的脉冲去"拉"到对应角度。如果第一个脉冲就是一个离当前位置很远的角度，
 * 舵机会全力输出力矩猛甩过去。SG90 空载时这个冲击足以把减速齿轮的齿打崩，
 * 也会把内部位置电位器的滑片撞坏（电位器没有过行程保护）。
 *
 * 1500µs = 90° 是 SG90 厂家标定的机械中位。从"随机位置"转向它，
 * 最多也就 90° 的行程，而且中位附近齿轮回差最小、最稳。
 * 这是实机调试里最省事也最安全的一条经验。
 * ==========================================================================*/
static void sg90_safe_init(void)
{
    /* pwm_init() 刚跑完时 CCR 是 0（0% 占空比），必须立刻改成中位脉宽。
     * 注意不要写成 pwm_init(TIM4_BASE, 1u, 2500u) —— 那是把周期当成了脉宽，
     * 等于让输出一直保持高电平，舵机会死死顶在 180° 不放。 */
    pwm_set_us(TIM4_BASE, 1u, SERVO_PULSE_MID);

    /* 全题唯一一次 delay，而且只发生在开机阶段。
     * 此时还没有任何功能在跑，串口也才刚起来，这里等 300ms 完全可以接受。
     * 换成运行期就必须靠 millis() 比时间戳，绝不能这样原地卡住。 */
    delay_ms(SERVO_CENTER_HOLD);
}

int main(void)
{
    /* ---- 时钟与时基 ---- */
    clock_init();
    dwt_init();
    timer_ms_init();              /* TIM6 每 1ms 中断一次 → millis() 可用 */

    /* ---- 调试串口 USART1 ---- */
    gpio_af(UART_TX, 7u);  gpio_mode(UART_TX, MODE_AF, PULL_UP, SPEED_HIGH);
    gpio_af(UART_RX, 7u);  gpio_mode(UART_RX, MODE_AF, PULL_UP, SPEED_HIGH);
    uart_init(USART1_BASE, g_pclk2_hz, 115200u);
    uart_puts(USART1_BASE, "\r\nQ5 servo-pot (board) ready\r\n");
    uart_puts(USART1_BASE, "pot 0..4095 -> servo 0..180deg, centered first\r\n");

    /* ---- 电位器分压 → PA0 (ADC1_IN0) ---- */
    adc_init(PIN_POT);

    /* ---- 舵机 PWM：TIM4_CH1 → PB6 ----
     * ★ 必须自己合 TIM4 的时钟闸：pwm_init() 只配寄存器不开 RCC，
     *   定时器时钟没开时寄存器写不生效，输出脚上一个沿都不会有。
     *   APB1ENR 的位序：bit0=TIM2 bit1=TIM3 bit2=TIM4。 */
    gpio_af(PIN_SIG, 2u);                       /* PB6 复用为 TIM4_CH1 */
    gpio_mode(PIN_SIG, MODE_AF, PULL_NONE, SPEED_HIGH);
    RCC_APB1ENR |= (1u << 2);                    /* TIM4EN */
    pwm_init(TIM4_BASE, 1u, SERVO_PERIOD);

    /* ★ 全题只 pwm_init() 一次。
     *   它会重设 PSC/ARR，一旦周期被别的代码改成不是 20ms，
     *   舵机就再也认不出自己的位置了。所以下面调角度一律走
     *   pwm_set_us()——它只改 CCR，周期纹丝不动。 */
    sg90_safe_init();

    for (;;) {
        /* ============= 真实采样 =============
         * 16 次平均。电位器滑片是机械触点，单次采样会在末尾几十个 LSB 里抖，
         * 直接拿去当角度，舵机会在目标位置不停小幅抽搐——
         * 这是实物上最常见的"舵机嗡嗡抖"，绝大多数情况就是采样没滤波。 */
        uint32_t adc  = adc_read_pin_avg(PIN_POT, ADC_AVG);
        uint32_t deg  = adc_to_deg(adc);
        uint32_t pulse = deg_to_pulse(deg);

        /* ============= 真实输出 =============
         * 写 CCR 就是舵机的"整个应用层输出"。
         * 有了 CCR 的预装载（OC1PE），新脉宽在下一个 20ms 周期边界统一生效，
         * 不会出现"半个周期宽度不对"的畸形脉冲——那一下抖动对舵机就是一次冲击。 */
        pwm_set_us(TIM4_BASE, 1u, pulse);

        /* ============= 演示辅助：把 ADC 值和算出来的角度打出来 =============
         * 现场验收时老师会同时盯着电位器和串口，能直观证明
         * "角度 = 4095/180 × ADC" 这个映射确实在跑。 */
        uint32_t now = millis();
        if ((now - g_last_print) >= PRINT_MS) {
            g_last_print = now;
            uart_puts(USART1_BASE, "adc=");
            uart_putu(USART1_BASE, adc);
            uart_puts(USART1_BASE, " deg=");
            uart_putu(USART1_BASE, deg);
            uart_puts(USART1_BASE, " pulse=");
            uart_putu(USART1_BASE, pulse);
            uart_puts(USART1_BASE, "us\r\n");
        }
    }
}