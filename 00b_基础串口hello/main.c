/* ============================================================================
 * lesson2_uart_hello/main.c —— L2：用 UART4 打印 "hello"，Renode 抓串口
 * ----------------------------------------------------------------------------
 * 【L2 是干什么的？】
 *   L1 是让芯片"动一个引脚"（点灯，芯片自己玩）；
 *   L2 是让芯片"开口说话"——通过串口 UART 把字符串发给电脑。
 *   你可以把 UART 想成芯片和电脑之间的一根"电话线"。
 *   笔试第 9 题（电脑发指令控制单片机）、第 10 题（单片机发"角度:距离"给电脑
 *   建图，也就是雷达项目）全都靠这根线。没有 L2，固件就是个哑巴。
 *
 * 【本文件做的事】
 *   1) 初始化 UART4（开时钟、设波特率、使能发送）；
 *   2) 写一个"发一个字节"的函数 uart_putc；
 *   3) 用它循环发 "hello from L2 (UART4)\r\n"。
 *   电脑端用 Renode 把 UART4 发出的字节直接写进 uart4.log（见 watch_uart.py）。
 *
 * 【UART 是什么（直觉）】
 *   一种最古老的串口：一根 TX 线，按固定速度（波特率）把一个字节拆成
 *   "起始位 + 8 个数据位 + 停止位"，一位一位电平平铺出去。我们只发不收。
 * ==========================================================================*/

#include <stdint.h>   /* 编译器自带的头文件，提供 uint32_t 这种"固定32位"类型 */

/* ----------------------------------------------------------------------------
 * MMIO 宏：把一个数字地址变成"可以读写的硬件寄存器"。
 *   (uint32_t *)(addr)  把整数地址转成"指向32位数的指针"
 *   *( ... )            取这个地址里的内容（左值，可读写）
 *   volatile            告诉编译器：别优化，每次都真的去读/写（硬件会自己变）
 * 这是 L1 就学过的核心宏，这里再出现一次，混个脸熟。
 * --------------------------------------------------------------------------*/
#define MMIO(addr) (*(volatile uint32_t *)(addr))

/* ============================================================================
 * 第一组寄存器：RCC（复位与时钟控制）—— 给外设上电
 * ==========================================================================
 * UART4 挂在 APB1 这条总线上，它的时钟开关在 RCC_APB1ENR 里。
 *   RCC 基址 = 0x40023800，APB1ENR 偏移 = 0x40，所以地址 = 0x40023840。
 *   UART4 对应第 19 位（查 STM32F4 手册得到，不用背）。
 * 和 L1 开 GPIOD 时钟完全一个套路：用任何外设前，先给它上电。
 * --------------------------------------------------------------------------*/
#define RCC_APB1ENR       MMIO(0x40023800u + 0x40u)  /* APB1 外设时钟使能寄存器 */
#define RCC_APB1ENR_UART4 (1u << 19)                  /* UART4 的时钟位 = 第19位 */

/* ============================================================================
 * 第二组寄存器：UART4 本身（基址 0x40004C00）
 * ==========================================================================
 * 一个 UART 外设有好几个寄存器，都在基址上叠加偏移：
 *   SR  (偏移0x00) 状态寄存器：里面某一位=1 表示"可以发下一个字节了"
 *   DR  (偏移0x04) 数据寄存器：往这写一个字节，硬件就从 TX 发出去
 *   BRR (偏移0x08) 波特率寄存器：决定发多快
 *   CR1 (偏移0x0C) 控制寄存器1：打开 UART、打开发送器
 * --------------------------------------------------------------------------*/
#define UART4_SR  MMIO(0x40004C00u + 0x00u)  /* 状态寄存器 Status Register */
#define UART4_DR  MMIO(0x40004C00u + 0x04u)  /* 数据寄存器 Data Register */
#define UART4_BRR MMIO(0x40004C00u + 0x08u)  /* 波特率寄存器 Baud Rate Register */
#define UART4_CR1 MMIO(0x40004C00u + 0x0Cu)  /* 控制寄存器1 Control Register 1 */

#define UART_SR_TXE (1u << 7)
/* TXE = Transmit Data Register Empty（发送数据寄存器空）
 * 它是 SR 的第 7 位：
 *   TXE=0  -> DR 里还有字节没发完，忙，不能写下一个
 *   TXE=1  -> DR 空了，可以写下一个字节
 * 我们发字节前就轮询这一位。 */

/* ================= 启动代码（和 L1 完全相同，先照抄、略过细节） =================
 * 作用：上电后设栈指针、把 .data 从 Flash 拷到 RAM、把 .bss 清零，然后调用 main。
 * L1 已经逐行注释过，这里不重复。你现在只需要知道：main() 是从这里被调用的。 */
extern uint32_t _estack, _sidata, _sdata, _edata, _sbss, _ebss;
typedef void (*isr_t)(void);
void Reset_Handler(void);
void Default_Handler(void);
int  main(void);

__attribute__((section(".isr_vector"), used))
isr_t vector_table[16] = {
    (isr_t)&_estack, Reset_Handler,
    Default_Handler, Default_Handler, Default_Handler, Default_Handler,
    Default_Handler, 0, 0, 0, 0, Default_Handler, Default_Handler,
    0, Default_Handler, Default_Handler,
};

__attribute__((naked))
void Reset_Handler(void)
{
    __asm volatile ("ldr r0, =_estack\n\t" "mov sp, r0\n\t" : : : "r0");
    for (uint32_t *p = &_sdata, *s = &_sidata; p < &_edata;) *p++ = *s++;
    for (uint32_t *p = &_sbss; p < &_ebss;) *p++ = 0;
    (void)main();
    for (;;) ;
}
void Default_Handler(void) { for (;;) ; }

/* ================= 用户代码从这里开始（重点读这一段） ================= */

/* 最简单的忙等待：和 L1 一样，靠空转 n 圈来拖时间。
 * 参数加 volatile 是防止编译器发现"这循环没用"把它优化掉。 */
static void delay(volatile uint32_t n)
{
    while (n--)          /* n 从传入值开始，每次减 1，减到 0 退出 */
        __asm__("nop");  /* nop = 空操作指令，纯粹占一个周期拖时间 */
}

/* ----------------------------------------------------------------------------
 * uart_init：UART4 初始化，就三行
 * --------------------------------------------------------------------------*/
static void uart_init(void)
{
    /* 第 1 行：开时钟。
     * 用 |= 而不是 =，是因为 RCC_APB1ENR 里还管着 APB1 上其它很多外设
     * （SPI、I2C、其它 UART……），我们只想把第 19 位置 1，其它位保持不动。 */
    RCC_APB1ENR |= RCC_APB1ENR_UART4;

    /* 第 2 行：设波特率。
     * BRR 决定"每秒发多少位"。真芯片公式：BRR = 总线频率 / (16 * 波特率)。
     * 这里写 0x682 是范本项目沿用的"115200 风格"值。
     * 重点：Renode 的文件后端不校验波特率，它只关心你往 DR 写了哪个字节，
     * 所以这个值写啥都能跑，上真板时再按实际时钟认真算。
     * 这里用 = 直接赋值，因为 BRR 是 UART4 私有的、我们从头初始化它。 */
    UART4_BRR = 0x682u;

    /* 第 3 行：使能。0x2008 同时开了两个开关：
     *   第 13 位 0x2000 = UE (UART Enable)  打开整个 UART 外设（总电源）
     *   第 3 位  0x0008 = TE (Transmitter Enable) 打开发送器（"嘴"的开关）
     * 我们只发不收，所以没开第 2 位 RE（接收器）。
     * 0x2000 | 0x0008 = 0x2008。 */
    UART4_CR1 = 0x2008u;

    /* 注意：真硬件上还要把 PA0 或 PC10 配成"复用功能 AF8"，才能把 UART4 的
     * TX 信号引到芯片外部引脚上。但 Renode 在 UART 外设这一层就把字节捕获到
     * 文件了，不经过引脚，所以这里不用配 GPIO——这是"仿真器建模到哪用到哪"。 */
}

/* ----------------------------------------------------------------------------
 * uart_putc：发一个字符（最核心的函数，逐行讲）
 *   入口参数 c = 要发的那个字符（比如 'h'）
 * --------------------------------------------------------------------------*/
static void uart_putc(char c)
{
    /* 第一步：等"发送寄存器空"。
     *   UART4_SR & UART_SR_TXE  —— 用 & 把 SR 里除了第 7 位以外的位都屏蔽掉，
     *                              只看第 7 位（TXE）。
     *   == 0u                   —— 如果结果是 0，说明 TXE=0，也就是还没发完、忙。
     *   while (...) ;           —— 忙就一直空转等（分号就是循环体，什么都不做）。
     * 等到 TXE 变成 1，条件不成立，退出循环，说明可以写下一个字节了。
     * 这种"死等一个标志位"叫轮询(polling)，是和硬件打交道最朴素的方式。 */
    while ((UART4_SR & UART_SR_TXE) == 0u)
        ;

    /* 第二步：把字符写进数据寄存器 DR，硬件就自动按"起始位+8位+停止位"从 TX 发出去。
     * (uint8_t)c  先把 char 转成 0~255 的无符号字节（char 可能是负数，先兜底）
     * (uint32_t)  再转成 32 位，因为 DR 是 32 位寄存器 */
    UART4_DR = (uint32_t)(uint8_t)c;
}

/* ----------------------------------------------------------------------------
 * uart_puts：发一整串字符（字符串）
 *   入口 s = 指向字符串第一个字符的指针
 *   C 语言的字符串以 '\0'（数值 0）结尾，比如 "hi" 在内存里是 'h','i','\0'
 * --------------------------------------------------------------------------*/
static void uart_puts(const char *s)
{
    while (*s)              /* *s = 当前指针指向的字符；非 0 就继续（没到结尾） */
        uart_putc(*s++);    /* 先把当前字符 *s 发出去，再 s++ 指针移到下一个字符 */
}

/* ----------------------------------------------------------------------------
 * main：程序入口
 * --------------------------------------------------------------------------*/
int main(void)
{
    uart_init();   /* 先把 UART4 初始化好（开电、设速度、张嘴） */

    /* 无限循环：发一行 hello，等一会儿，再发一行…… */
    for (;;) {
        /* "hello from L2 (UART4)\r\n" 是字符串常量，存在 Flash 里，
         * 这里把它的首地址传给 uart_puts。
         * \r = 回车（光标回到行首），\n = 换行（到下一行）；
         * 串口惯例用 \r\n 两个字符换行，电脑上的串口助手才能正确显示。 */
        uart_puts("hello from L2 (UART4)\r\n");

        delay(300000);   /* 发完一行等约 0.375 秒，再发下一行 */
    }
}
