/* ============================================================================
 * 00b_基础串口hello/main_board.c —— L2 串口打印 · 真板版
 * ----------------------------------------------------------------------------
 * 【和仿真版 main.c 的关系】
 *   仿真版 main.c：手写 UART4 的 SR/DR/BRR/CR1，循环发 "hello from L2 (UART4)"，
 *                  Renode 把字节写进 uart4.log。
 *   真板版        ：同样的"逐字节阻塞发送 + 发整串"逻辑原样搬过来，
 *                  换成 USART1（PA9/PA10，AF7）+ 公共层的 uart_init/uart_puts。
 *
 *   换掉的只有 IO 层，**应用逻辑一行没动**。验收时被问可以直接说：是同一套。
 *
 *   另外多打了两样东西：固件版本号 + 上电后经过的毫秒数。
 *   这不是花活，是真板调试的基本功：
 *     · 版本号  → 烧完板子第一件事是确认"烧进去的到底是哪一份"，烧错/没烧成功一眼看穿；
 *     · 毫秒数  → 证明 millis() 这个硬件时基真的在走，而且量出来的时间能对上，
 *                 后面 q09 的"闪烁必须用硬件定时器"才有验收依据。
 *
 * ------------------------------------------------------------------
 * 一、接线（换板子只改下面那张引脚表）
 * ------------------------------------------------------------------
 *   PA9  (USART1_TX, AF7) ── USB-TTL 的 RXD        115200-8-N-1
 *   PA10 (USART1_RX, AF7) ── USB-TTL 的 TXD
 *   USB-TTL 的 GND 必须和板子的 GND 相连。
 *
 *   ⚠ 共地是最容易漏的一步：不接地时串口助手可能收到（对方看到的电平相对自己的地）
 *     却收出乱码，或者干脆一个字节都收不到。老师问"为什么没输出"，
 *     十次里八次是这根地线没接。
 *   ⚠ 电压：USB-TTL 模块的 VCC 别接到 5V 上再让信号脚回来，PA10 是 3.3V 域的输入，
 *     用 5V 供电的 CH340 板需要确认它的 IO 电平是否也是 3.3V（多数带电平转换的可以）。
 *
 * ------------------------------------------------------------------
 * 二、这题真正要讲的东西
 * ------------------------------------------------------------------
 *   ① 串口分频 BRR 是**按 PCLK 算**的，不是按主频。
 *      USART1 挂在 APB2，APB2 被二分成 84MHz，所以 BRR = 84M/115200 = 728.9 → 728。
 *      波特率差一点点没事（误差 <2% 就不丢字节），但如果忘了 APB2 分频、
 *      按 168M 去算，误差就是 50%，收到的全是乱码。
 *   ② USART1 的信号要先配 AF7（AFRL/AFRH）再配 MODER=复用，两步缺一个都不出脚。
 *   ③ TXE 轮询是"阻塞"的：发完一个字节要等移位寄存器把上一个吐完。
 *      这在"只发几十字节"的场景没问题，但要知道它的代价——
 *      115200 下发一个字节约 87µs，发一屏汉字要几毫秒，期间 CPU 什么都干不了。
 *      所以后面 q03 刷 OLED、q09 收命令都改成"限频/非阻塞"的写法。
 * ==========================================================================*/

#include "stm32f4_common.h"

/* ============================ 引脚表 ============================
 * 换板子只改这一段。USART1 的 AF7 固定是 PA9/PA10；
 * 真要换引脚（比如改用 USART2 的 PA2/PA3），还得同时改 AF 号和 uart_init 的 base。 */
#define UART_TX     PA9    /* USART1_TX → AF7 */
#define UART_RX     PA10   /* USART1_RX → AF7 */

#define UART_BASE   USART1_BASE
#define UART_BAUD   115200u

/* 版本号：每次改了串口输出的内容就把这行改掉。
 * 烧录后第一行输出的就是这个串，现场确认"烧的是哪份代码"只看它。 */
#define FW_VERSION  "v1.0.0"
#define FW_BOARD    "STM32F407 / USART1 / PA9,PA10"

int main(void)
{
    /* ---- 时钟与时基 ---- */
    clock_init();      /* 8MHz → PLL → 168MHz。这一步不做，下面 BRR 算出来是错的 */
    dwt_init();        /* DWT 周期计数器（delay_us 用） */
    timer_ms_init();   /* TIM6 每 1ms 中断 → millis() 可用，也是下面报时的来源 */

    /* ---- 串口 ----
     * 先配 AF 号再配模式：gpio_af() 写的是 AFRL/AFRH（哪个外设接管这个脚），
     * gpio_mode(MODE_AF) 写的是 MODER（把脚从通用 GPIO 交给复用功能）。
     * 只配 MODER 不配 AF，信号出不了芯片；只配 AF 不配 MODER，脚还是普通 GPIO。
     *
     * 为什么两个脚都用 PULL_UP：USART 是单端信号，靠空闲态高电平区分。
     * 板上如果已经有 USB-TTL 的上拉，这里再开内部上拉是无害的（两个上拉并联）。
     * 反过来如果这是空悬的 RX，浮空读进来的是随机电平，会不停产生噪声字节。 */
    gpio_af(UART_TX, 7u);  gpio_mode(UART_TX, MODE_AF, PULL_UP, SPEED_HIGH);
    gpio_af(UART_RX, 7u);  gpio_mode(UART_RX, MODE_AF, PULL_UP, SPEED_HIGH);

    /* 波特率按 PCLK2 算（USART1 挂 APB2 = 84MHz），不是按 168MHz 主频算。
     * 写错了不会立刻报错，只会让串口助手收到乱码，是最典型的"静默失败"。 */
    uart_init(UART_BASE, g_pclk2_hz, UART_BAUD);

    /* ---- 欢迎信息 ----
     * 行首用 \r\n：串口助手的终端是行结束符敏感的，
     * 只发 '\n' 的话，光标只下移不回行首，多行输出会连成一片。 */
    uart_puts(UART_BASE, "\r\n==========================\r\n");
    uart_puts(UART_BASE, " L2  uart hello (board)\r\n");
    uart_puts(UART_BASE, " fw    : " FW_VERSION "\r\n");
    uart_puts(UART_BASE, " board : " FW_BOARD "\r\n");
    uart_puts(UART_BASE, " baud  : 115200-8-N-1\r\n");
    uart_puts(UART_BASE, "==========================\r\n");

    uint32_t last_report = millis();

    for (;;) {
        /* 每 1000ms 打一行"上电后经过了多少毫秒"。
         *
         * millis() 的来源是 TIM6 的 1ms 更新中断，不是软件数出来的，
         * 所以这个数字可以直接当成计时器用：量出来和电脑上的秒表差几十毫秒是正常的
         * （中断响应 + 串口发送本身的耗时），但差几秒就说明时基配错了。
         *
         * 这里不用 delay_ms(1000) 去卡 1 秒：那会让 CPU 空转，
         * 而且一旦后面要加别的任务（按键、刷屏），就没有插入的地方了。
         * "记下下一次该干活的时刻"是裸机里最该养成的习惯。 */
        if ((millis() - last_report) >= 1000u) {
            last_report += 1000u;      /* 用累加而不是 last_report = millis()：
                                         * 前者不会累积执行耗时，长期看误差不漂 */

            uart_puts(UART_BASE, "uptime = ");
            uart_putu(UART_BASE, millis());      /* 手写十进制转换，不依赖 printf */
            uart_puts(UART_BASE, " ms\r\n");
        }
    }
}